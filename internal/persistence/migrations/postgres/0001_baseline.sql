CREATE TABLE users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email TEXT UNIQUE NOT NULL,
  username TEXT UNIQUE NOT NULL,
  password_hash TEXT NOT NULL,
  avatar_url TEXT,
  created_at TEXT NOT NULL DEFAULT (to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')),
  updated_at TEXT NOT NULL DEFAULT (to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')),
  is_verified BIGINT DEFAULT 0,
  verified_at TEXT,
  is_sponsor BIGINT DEFAULT 0,
  sponsor_since TEXT,
  last_login TEXT,
  last_ip TEXT,
  last_ip_location TEXT,
  last_ip_updated_at TEXT
, token_version BIGINT NOT NULL DEFAULT 0);

CREATE TABLE playlists (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL,
  name TEXT NOT NULL,
  type TEXT NOT NULL CHECK (type IN ('local', 'synced')),
  is_default BIGINT NOT NULL DEFAULT 0,
  source TEXT,
  source_playlist_id TEXT,
  content_revision BIGINT NOT NULL DEFAULT 0,
  order_revision BIGINT NOT NULL DEFAULT 0,
  binding_version BIGINT NOT NULL DEFAULT 0,
  active_snapshot_id BIGINT,
  sync_status TEXT NOT NULL DEFAULT 'idle'
    CHECK (sync_status IN ('idle', 'syncing', 'ready', 'error')),
  last_synced_at TEXT,
  created_at TEXT NOT NULL DEFAULT (to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')),
  updated_at TEXT NOT NULL DEFAULT (to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')), sync_revision BIGINT NOT NULL DEFAULT 0,
  CHECK (
    (type = 'local' AND source IS NULL AND source_playlist_id IS NULL) OR
    (type = 'synced' AND source IS NOT NULL AND source_playlist_id IS NOT NULL)
  )
);

CREATE TABLE playlist_tracks_catalog (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  source TEXT NOT NULL,
  source_track_id TEXT NOT NULL,
  name TEXT NOT NULL,
  artists TEXT NOT NULL,
  album TEXT NOT NULL,
  pic_url TEXT NOT NULL DEFAULT '',
  source_ids_json TEXT,
  created_at TEXT NOT NULL DEFAULT (to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')),
  updated_at TEXT NOT NULL DEFAULT (to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')),
  UNIQUE(source, source_track_id)
);

CREATE TABLE playlist_snapshots (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  playlist_id BIGINT NOT NULL,
  binding_version BIGINT NOT NULL,
  expected_count BIGINT NOT NULL,
  item_count BIGINT NOT NULL DEFAULT 0,
  status TEXT NOT NULL DEFAULT 'staging'
    CHECK (status IN ('staging', 'complete', 'retired')),
  created_at TEXT NOT NULL DEFAULT (to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')),
  completed_at TEXT,
  FOREIGN KEY (playlist_id) REFERENCES playlists(id) ON DELETE CASCADE
);

CREATE TABLE local_playlist_items (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  playlist_id BIGINT NOT NULL,
  track_id BIGINT NOT NULL,
  rank BIGINT NOT NULL,
  added_at TEXT NOT NULL DEFAULT (to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')),
  FOREIGN KEY (playlist_id) REFERENCES playlists(id) ON DELETE CASCADE,
  FOREIGN KEY (track_id) REFERENCES playlist_tracks_catalog(id),
  UNIQUE(playlist_id, track_id)
);

CREATE TABLE playlist_snapshot_items (
  snapshot_id BIGINT NOT NULL,
  track_id BIGINT NOT NULL,
  source_position BIGINT NOT NULL,
  occurrence_index BIGINT NOT NULL DEFAULT 0,
  FOREIGN KEY (snapshot_id) REFERENCES playlist_snapshots(id) ON DELETE CASCADE,
  FOREIGN KEY (track_id) REFERENCES playlist_tracks_catalog(id),
  PRIMARY KEY (snapshot_id, source_position, occurrence_index)
);

